def _norm(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()
    df.columns = [str(c).replace("\ufeff", "").strip() for c in df.columns]
    return df


def _require(df: pd.DataFrame, name: str, cols: Sequence[str]) -> None:
    missing = [c for c in cols if c not in df.columns]
    if missing:
        raise ValueError(f"{name}: missing required columns {missing}")


def _unique(df: pd.DataFrame, cols: Sequence[str], name: str) -> None:
    n = int(df.duplicated(list(cols), keep=False).sum())
    if n:
        raise ValueError(f"{name}: key {list(cols)} is not unique; duplicate rows={n:,}")


def _safe_div(num: pd.Series, den: pd.Series) -> pd.Series:
    return pd.to_numeric(num, errors="coerce") / pd.to_numeric(den, errors="coerce").replace(0, np.nan)


def _iso_date(s: pd.Series) -> pd.Series:
    s = pd.to_datetime(s, errors="coerce")
    out = s.dt.strftime("%Y-%m-%d")
    return out.where(s.notna(), pd.NA)


def _max_abs_diff(a: pd.Series, b: pd.Series) -> float:
    d = (pd.to_numeric(a, errors="coerce") - pd.to_numeric(b, errors="coerce")).abs()
    return float(d.max()) if len(d) and d.notna().any() else 0.0


class DWReader:
    """Find the DW root inside a directory or ZIP, then read known DW tables."""

    def __init__(self, source: Path):
        self.source = Path(source)
        if not self.source.exists():
            raise FileNotFoundError(f"Input not found: {self.source}")
        self.tmp: Optional[tempfile.TemporaryDirectory] = None
        self.root: Path
        if self.source.is_file():
            if not zipfile.is_zipfile(self.source):
                raise ValueError("DW input file must be a ZIP archive")
            self.tmp = tempfile.TemporaryDirectory(prefix="problem3_dw_")
            with zipfile.ZipFile(self.source, "r") as zf:
                zf.extractall(self.tmp.name)
            base = Path(self.tmp.name)
        else:
            base = self.source

        candidates = [base] + [p for p in base.rglob("*") if p.is_dir()]
        self.root = None  # type: ignore
        for c in candidates:
            if (c / "dimensions").is_dir() and (c / "facts").is_dir():
                self.root = c
                break
        if self.root is None:
            self.close()
            raise FileNotFoundError("Could not find DW root containing dimensions/ and facts/")

    def close(self):
        if self.tmp is not None:
            self.tmp.cleanup()
            self.tmp = None

    def read(self, relative: str, dtype: Optional[dict] = None) -> pd.DataFrame:
        p = self.root / relative
        if not p.exists():
            raise FileNotFoundError(f"Required DW file missing: {relative}")
        kw = dict(low_memory=False, encoding="utf-8-sig")
        if dtype:
            kw["dtype"] = dtype
        return _norm(pd.read_csv(p, **kw))


@dataclass
class ValidationRow:
    validation_id: str
    validation_check: str
    expected: str
    actual: str
    status: str
    severity: str = "ERROR"
    details: str = ""


class GoldV2:
    def __init__(self, input_path: Path, output_dir: Path,
                 included_statuses: Optional[List[str]] = None, tolerance: float = 0.01):
        self.input_path = Path(input_path)
        self.output_dir = Path(output_dir)
        self.facts_dir = self.output_dir / "facts"
        self.marts_dir = self.output_dir / "marts"
        self.reports_dir = self.output_dir / "reports"
        self.included_statuses = [s.strip() for s in (included_statuses or []) if s.strip()]
        self.tolerance = float(tolerance)
        self.run_timestamp_utc = datetime.now(timezone.utc).isoformat()
        self.validation: List[ValidationRow] = []
        self.reconciliation_rows: List[dict] = []

    def prepare(self):
        if self.output_dir.exists():
            shutil.rmtree(self.output_dir)
        self.facts_dir.mkdir(parents=True, exist_ok=True)
        self.marts_dir.mkdir(parents=True, exist_ok=True)
        self.reports_dir.mkdir(parents=True, exist_ok=True)

    def load_dw(self):
        r = DWReader(self.input_path)
        try:
            self.dim_date = r.read("dimensions/DIM_DATE.csv")
            self.dim_customer = r.read("dimensions/DIM_CUSTOMER.csv", dtype={"zip": "string"})
            self.dim_geo = r.read("dimensions/DIM_GEOGRAPHY.csv", dtype={"zip": "string"})
            self.dim_product = r.read("dimensions/DIM_PRODUCT.csv")
            self.dim_status = r.read("dimensions/DIM_ORDER_STATUS.csv")
            self.dw_line = r.read("facts/FACT_SALES_LINE.csv.gz")
            self.dw_order = r.read("facts/FACT_ORDER.csv.gz")
            self.dw_monthly_snapshot = r.read("facts/FACT_CUSTOMER_MONTHLY_SNAPSHOT.csv.gz")
        finally:
            r.close()

        _require(self.dim_date, "DIM_DATE", ["date_key", "full_date", "day_name", "month", "year", "year_month"])
        _require(self.dim_customer, "DIM_CUSTOMER", ["customer_key", "customer_id", "zip", "geo_key", "signup_date", "gender", "age_group", "acquisition_channel"])
        _require(self.dim_geo, "DIM_GEOGRAPHY", ["geo_key", "zip", "city", "district", "region"])
        _require(self.dim_product, "DIM_PRODUCT", ["product_key", "product_id", "category"])
        _require(self.dim_status, "DIM_ORDER_STATUS", ["order_status_key", "order_status"])
        _require(self.dw_line, "FACT_SALES_LINE", ["sales_line_key", "order_item_id", "order_id", "date_key", "customer_key", "product_key", "order_status_key", "quantity", "unit_price", "discount_amount", "gross_sales", "net_sales"])
        _require(self.dw_order, "FACT_ORDER", ["order_key", "order_id", "date_key", "customer_key", "order_status_key", "order_value", "basket_quantity", "distinct_products", "line_count", "payment_value"])
        _require(self.dw_monthly_snapshot, "FACT_CUSTOMER_MONTHLY_SNAPSHOT", ["snapshot_month_key", "customer_key", "monthly_order_count", "monthly_quantity", "monthly_net_sales"])

        for df, keys, name in [
            (self.dim_date, ["date_key"], "DIM_DATE"),
            (self.dim_customer, ["customer_key"], "DIM_CUSTOMER"),
            (self.dim_customer, ["customer_id"], "DIM_CUSTOMER business key"),
            (self.dim_geo, ["geo_key"], "DIM_GEOGRAPHY"),
            (self.dim_product, ["product_key"], "DIM_PRODUCT"),
            (self.dim_product, ["product_id"], "DIM_PRODUCT business key"),
            (self.dim_status, ["order_status_key"], "DIM_ORDER_STATUS"),
            (self.dw_line, ["sales_line_key"], "FACT_SALES_LINE"),
            (self.dw_line, ["order_item_id"], "FACT_SALES_LINE order_item_id"),
            (self.dw_order, ["order_id"], "FACT_ORDER order_id"),
            (self.dw_monthly_snapshot, ["snapshot_month_key", "customer_key"], "FACT_CUSTOMER_MONTHLY_SNAPSHOT"),
        ]:
            _unique(df, keys, name)

        self.dim_date["full_date"] = pd.to_datetime(self.dim_date["full_date"], errors="coerce")
        self.dim_customer["signup_date"] = pd.to_datetime(self.dim_customer["signup_date"], errors="coerce")

        # Status universe from conformed dimension.
        self.available_statuses = sorted(self.dim_status["order_status"].dropna().astype(str).tolist())
        self.status_policy = "ALL STATUSES"
        if self.included_statuses:
            allowed = {s.lower() for s in self.included_statuses}
            unknown = sorted(allowed - {s.lower() for s in self.available_statuses})
            if unknown:
                raise ValueError(f"Unknown included statuses: {unknown}; available={self.available_statuses}")
            status_keys = set(self.dim_status.loc[self.dim_status["order_status"].astype(str).str.lower().isin(allowed), "order_status_key"])
            self.dw_order_scope = self.dw_order[self.dw_order["order_status_key"].isin(status_keys)].copy()
            valid_orders = set(self.dw_order_scope["order_id"].tolist())
            self.dw_line_scope = self.dw_line[self.dw_line["order_id"].isin(valid_orders)].copy()
            self.status_policy = "FILTERED: " + ",".join(self.included_statuses)
        else:
            self.dw_order_scope = self.dw_order.copy()
            self.dw_line_scope = self.dw_line.copy()

    def build_fact_item(self):
        f = self.dw_line_scope.copy()
        f = f.merge(
            self.dim_customer[["customer_key", "customer_id"]], on="customer_key", how="left", validate="many_to_one"
        )
        f = f.merge(
            self.dim_product[["product_key", "product_id", "category"]], on="product_key", how="left", validate="many_to_one"
        )
        f = f.merge(
            self.dim_date[["date_key", "full_date", "year", "month", "year_month", "day_name"]],
            on="date_key", how="left", validate="many_to_one"
        )
        f = f.rename(columns={
            "full_date": "order_date", "day_name": "day_of_week",
            "gross_sales": "line_gross_sales", "net_sales": "line_net_sales"
        })
        cols = [
            "order_item_id", "order_id", "customer_id", "order_date", "year", "month", "year_month", "day_of_week",
            "product_id", "category", "quantity", "unit_price", "discount_amount", "line_gross_sales", "line_net_sales"
        ]
        self.fact_item = f[cols].sort_values("order_item_id").reset_index(drop=True)

    def build_fact_order(self):
        f = self.dw_order_scope.copy()
        f = f.merge(self.dim_customer[["customer_key", "customer_id"]], on="customer_key", how="left", validate="many_to_one")
        f = f.merge(
            self.dim_date[["date_key", "full_date", "year_month", "day_name"]],
            on="date_key", how="left", validate="many_to_one"
        )
        f = f.merge(self.dim_status, on="order_status_key", how="left", validate="many_to_one")
        f = f.rename(columns={"full_date": "order_date", "day_name": "day_of_week"})
        cols = [
            "order_id", "customer_id", "order_date", "year_month", "day_of_week", "order_status",
            "order_value", "basket_quantity", "distinct_products", "line_count"
        ]
        self.fact_order = f[cols].sort_values("order_id").reset_index(drop=True)

    def build_customer_category(self):
        cc = self.fact_item.groupby(["customer_id", "category"], dropna=False, as_index=False).agg(
            orders=("order_id", "nunique"), units=("quantity", "sum"), net_sales=("line_net_sales", "sum")
        )
        cc["net_sales"] = cc["net_sales"].round(2)
        totals = cc.groupby("customer_id")["net_sales"].transform("sum")
        cc["revenue_share"] = np.where(totals != 0, cc["net_sales"] / totals, np.nan)
        cc = cc.sort_values(
            ["customer_id", "net_sales", "units", "category"],
            ascending=[True, False, False, True], na_position="last"
        ).reset_index(drop=True)
        cc["category_rank"] = cc.groupby("customer_id").cumcount() + 1
        cc["is_preferred_category"] = cc["category_rank"].eq(1)
        cc["revenue_share"] = cc["revenue_share"].round(4)
        self.customer_category = cc[[
            "customer_id", "category", "orders", "units", "net_sales", "revenue_share", "category_rank", "is_preferred_category"
        ]]

    def build_customer_360(self):
        profile = self.dim_customer[[
            "customer_key", "customer_id", "signup_date", "gender", "age_group", "acquisition_channel", "zip", "geo_key"
        ]].copy()
        profile = profile.merge(
            self.dim_geo[["geo_key", "city", "district", "region"]], on="geo_key", how="left", validate="many_to_one"
        ).drop(columns=["geo_key", "customer_key"])

        agg = self.fact_order.groupby("customer_id", as_index=False).agg(
            first_order_date=("order_date", "min"),
            last_order_date=("order_date", "max"),
            order_count=("order_id", "nunique"),
            total_quantity=("basket_quantity", "sum"),
            total_net_sales=("order_value", "sum"),
        )
        agg["total_net_sales"] = agg["total_net_sales"].round(2)

        intervals = self.fact_order[["customer_id", "order_id", "order_date"]].sort_values(
            ["customer_id", "order_date", "order_id"]
        ).copy()
        intervals["days_between"] = intervals.groupby("customer_id")["order_date"].diff().dt.days
        gaps = intervals.groupby("customer_id", as_index=False)["days_between"].mean().rename(
            columns={"days_between": "avg_days_between_orders"}
        )
        agg = agg.merge(gaps, on="customer_id", how="left", validate="one_to_one")

        c = profile.merge(agg, on="customer_id", how="left", validate="one_to_one")
        c["order_count"] = c["order_count"].fillna(0).astype("int64")
        c["total_quantity"] = c["total_quantity"].fillna(0).astype("int64")
        c["total_net_sales"] = c["total_net_sales"].fillna(0.0).astype(float).round(2)
        c["avg_order_value"] = _safe_div(c["total_net_sales"], c["order_count"]).round(2)
        c["avg_basket_size"] = _safe_div(c["total_quantity"], c["order_count"]).round(4)
        c["avg_days_between_orders"] = c["avg_days_between_orders"].round(2)
        c["customer_lifespan_days"] = (c["last_order_date"] - c["first_order_date"]).dt.days
        c["frequency"] = c["order_count"]
        c["monetary"] = c["total_net_sales"].round(2)
        c["historical_clv"] = c["total_net_sales"].round(2)

        buyers = c["order_count"].ge(1)
        if not buyers.any():
            raise ValueError("No buyers after status scope; cannot compute F/M segmentation")
        self.frequency_median = float(c.loc[buyers, "frequency"].median())
        self.monetary_median = float(c.loc[buyers, "monetary"].median())

        c["frequency_level"] = pd.Series(pd.NA, index=c.index, dtype="string")
        c["monetary_level"] = pd.Series(pd.NA, index=c.index, dtype="string")
        c.loc[buyers, "frequency_level"] = np.where(c.loc[buyers, "frequency"] >= self.frequency_median, "High", "Low")
        c.loc[buyers, "monetary_level"] = np.where(c.loc[buyers, "monetary"] >= self.monetary_median, "High", "Low")
        c["customer_type"] = np.select(
            [c["order_count"].eq(0), c["order_count"].eq(1), c["order_count"].ge(2)],
            ["No-purchase", "One-time", "Repeat"], default="Unknown"
        )
        c["customer_segment"] = pd.Series(pd.NA, index=c.index, dtype="string")
        for fl, ml, seg in [
            ("High", "High", "VIP"), ("Low", "High", "High-value"),
            ("High", "Low", "Potential"), ("Low", "Low", "Low-value")
        ]:
            mask = buyers & c["frequency_level"].eq(fl) & c["monetary_level"].eq(ml)
            c.loc[mask, "customer_segment"] = seg

        pref = self.customer_category.loc[self.customer_category["is_preferred_category"], [
            "customer_id", "category", "revenue_share"
        ]].rename(columns={"category": "preferred_category", "revenue_share": "preferred_category_share"})
        c = c.merge(pref, on="customer_id", how="left", validate="one_to_one")

        cols = [
            "customer_id", "signup_date", "gender", "age_group", "acquisition_channel", "zip", "city", "district", "region",
            "first_order_date", "last_order_date", "order_count", "total_quantity", "total_net_sales", "avg_order_value",
            "avg_basket_size", "avg_days_between_orders", "customer_lifespan_days", "frequency", "monetary",
            "frequency_level", "monetary_level", "customer_type", "customer_segment", "historical_clv",
            "preferred_category", "preferred_category_share"
        ]
        self.customer_360 = c[cols].sort_values("customer_id").reset_index(drop=True)

    def build_customer_monthly(self):
        # Derive from DW FACT_ORDER to respect optional status scope. The DW monthly snapshot
        # remains a reconciliation/performance source and is validated for ALL-STATUS runs.
        m = self.fact_order.groupby(["customer_id", "year_month"], as_index=False).agg(
            orders=("order_id", "nunique"), units=("basket_quantity", "sum"), net_sales=("order_value", "sum")
        )
        m["net_sales"] = m["net_sales"].round(2)
        m["avg_order_value"] = _safe_div(m["net_sales"], m["orders"]).round(2)
        m["avg_basket_size"] = _safe_div(m["units"], m["orders"]).round(4)
        m = m.merge(self.customer_360[["customer_id", "customer_type"]], on="customer_id", how="left", validate="many_to_one")
        self.customer_monthly = m[[
            "customer_id", "year_month", "orders", "units", "net_sales", "avg_order_value", "avg_basket_size", "customer_type"
        ]].sort_values(["customer_id", "year_month"]).reset_index(drop=True)

    @staticmethod
    def _time_agg(df: pd.DataFrame, group_col: str) -> pd.DataFrame:
        x = df.groupby(group_col, as_index=False).agg(
            orders=("order_id", "nunique"), customers=("customer_id", "nunique"),
            units=("basket_quantity", "sum"), net_sales=("order_value", "sum")
        )
        rep = df[df["customer_type"].eq("Repeat")].groupby(group_col)["customer_id"].nunique()
        one = df[df["customer_type"].eq("One-time")].groupby(group_col)["customer_id"].nunique()
        x["repeat_customers"] = x[group_col].map(rep).fillna(0).astype("int64")
        x["one_time_customers"] = x[group_col].map(one).fillna(0).astype("int64")
        x["net_sales"] = x["net_sales"].round(2)
        x["avg_order_value"] = _safe_div(x["net_sales"], x["orders"]).round(2)
        x["avg_basket_size"] = _safe_div(x["units"], x["orders"]).round(4)
        return x

    def build_customer_time(self):
        fo = self.fact_order.merge(self.customer_360[["customer_id", "customer_type"]], on="customer_id", how="left", validate="many_to_one")
        month = self._time_agg(fo, "year_month")
        month["time_grain"] = "MONTH"
        month["period_key"] = month["year_month"].astype(str)
        month["period_label"] = month["year_month"].astype(str)
        month = month.sort_values("period_key")

        weekday = self._time_agg(fo, "day_of_week")
        weekday["time_grain"] = "DAY_OF_WEEK"
        weekday["period_key"] = weekday["day_of_week"].map(WEEKDAY_CODE)
        weekday["period_label"] = weekday["day_of_week"]
        weekday["weekday_order"] = weekday["day_of_week"].map({d: i for i, d in enumerate(WEEKDAY_ORDER)})
        weekday = weekday.sort_values("weekday_order")

        cols = [
            "time_grain", "period_key", "period_label", "orders", "customers", "units", "net_sales",
            "avg_order_value", "avg_basket_size", "repeat_customers", "one_time_customers"
        ]
        self.customer_time = pd.concat([month[cols], weekday[cols]], ignore_index=True)

    def build_segment_summary(self):
        buyers = self.customer_360[self.customer_360["order_count"].ge(1)].copy()
        total_buyers = len(buyers)
        total_sales = float(buyers["total_net_sales"].sum())
        g = buyers.groupby("customer_segment", dropna=False).agg(
            customer_count=("customer_id", "count"), orders=("order_count", "sum"), units=("total_quantity", "sum"),
            net_sales=("total_net_sales", "sum"), avg_frequency=("frequency", "mean"), avg_monetary=("monetary", "mean"),
            avg_aov=("avg_order_value", "mean"), avg_basket_size=("avg_basket_size", "mean"),
            avg_historical_clv=("historical_clv", "mean")
        ).reindex(SEGMENT_ORDER)
        g["customer_count"] = g["customer_count"].fillna(0).astype("int64")
        g["orders"] = g["orders"].fillna(0).astype("int64")
        g["units"] = g["units"].fillna(0).astype("int64")
        g["net_sales"] = g["net_sales"].fillna(0).round(2)
        g["customer_share"] = g["customer_count"] / total_buyers if total_buyers else np.nan
        g["revenue_share"] = g["net_sales"] / total_sales if total_sales else np.nan
        for c, n in [("customer_share",4),("revenue_share",4),("avg_frequency",2),("avg_monetary",2),("avg_aov",2),("avg_basket_size",4),("avg_historical_clv",2)]:
            g[c] = g[c].round(n)
        g.index.name = "customer_segment"
        self.segment_summary = g.reset_index()[[
            "customer_segment", "customer_count", "customer_share", "orders", "units", "net_sales", "revenue_share",
            "avg_frequency", "avg_monetary", "avg_aov", "avg_basket_size", "avg_historical_clv"
        ]]

    def validate(self):
        tol = self.tolerance
        def add(i, check, expected, actual, ok, details="", severity="ERROR"):
            self.validation.append(ValidationRow(i, check, expected, actual, "PASS" if ok else "FAIL", severity, details))

        # Facts preserve the selected DW transaction universe.
        add("GV2-01", "Gold item fact row count = scoped DW line fact", str(len(self.dw_line_scope)), str(len(self.fact_item)), len(self.fact_item)==len(self.dw_line_scope))
        add("GV2-02", "Gold order fact row count = scoped DW order fact", str(len(self.dw_order_scope)), str(len(self.fact_order)), len(self.fact_order)==len(self.dw_order_scope))
        add("GV2-03", "Gold order_item_id unique and non-null", "0 duplicate / 0 null",
            f"dup={int(self.fact_item.order_item_id.duplicated().sum())}; null={int(self.fact_item.order_item_id.isna().sum())}",
            not self.fact_item.order_item_id.duplicated().any() and not self.fact_item.order_item_id.isna().any())
        add("GV2-04", "Gold order_id unique and non-null", "0 duplicate / 0 null",
            f"dup={int(self.fact_order.order_id.duplicated().sum())}; null={int(self.fact_order.order_id.isna().sum())}",
            not self.fact_order.order_id.duplicated().any() and not self.fact_order.order_id.isna().any())

        # Gold values equal DW values.
        line_dw = float(self.dw_line_scope["net_sales"].sum())
        line_gold = float(self.fact_item["line_net_sales"].sum())
        order_dw = float(self.dw_order_scope["order_value"].sum())
        order_gold = float(self.fact_order["order_value"].sum())
        add("GV2-05", "SUM Gold line_net_sales = SUM DW net_sales", f"diff <= {tol}", f"diff={abs(line_dw-line_gold):.6f}", abs(line_dw-line_gold)<=tol)
        add("GV2-06", "SUM Gold order_value = SUM DW order_value", f"diff <= {tol}", f"diff={abs(order_dw-order_gold):.6f}", abs(order_dw-order_gold)<=tol)
        add("GV2-07", "Gold line total = Gold order total", f"diff <= {tol}", f"diff={abs(line_gold-order_gold):.6f}", abs(line_gold-order_gold)<=tol)

        # DW payment reconciliation in the chosen scope.
        pay_total = float(self.dw_order_scope["payment_value"].sum())
        max_pay_diff = float((self.dw_order_scope["order_value"] - self.dw_order_scope["payment_value"]).abs().max())
        add("GV2-08", "Scoped DW order value reconciles with payment value", f"total/max diff <= {tol}",
            f"total_diff={abs(order_dw-pay_total):.6f}; max_order_diff={max_pay_diff:.6f}",
            abs(order_dw-pay_total)<=tol and max_pay_diff<=tol)

        # Dimension mapping / Gold profile coverage.
        add("GV2-09", "MART_CUSTOMER_360 row count = DIM_CUSTOMER", str(len(self.dim_customer)), str(len(self.customer_360)), len(self.customer_360)==len(self.dim_customer))
        missing_dim_values = int(self.fact_item[["customer_id","product_id","order_date"]].isna().any(axis=1).sum())
        add("GV2-10", "DW surrogate keys resolve to required Gold business attributes", "0 unresolved item rows", str(missing_dim_values), missing_dim_values==0)

        # Customer metric reconciliation.
        c_sales = float(self.customer_360["total_net_sales"].sum())
        c_units = int(self.customer_360["total_quantity"].sum())
        add("GV2-11", "Customer 360 Net Sales = Gold order total", f"diff <= {tol}", f"diff={abs(c_sales-order_gold):.6f}", abs(c_sales-order_gold)<=tol)
        add("GV2-12", "Customer 360 units = Gold order basket units", str(int(self.fact_order["basket_quantity"].sum())), str(c_units), c_units==int(self.fact_order["basket_quantity"].sum()))

        buyers = self.customer_360[self.customer_360["order_count"]>=1]
        no_purchase = self.customer_360[self.customer_360["order_count"]==0]
        one = int((buyers["customer_type"]=="One-time").sum())
        rep = int((buyers["customer_type"]=="Repeat").sum())
        add("GV2-13", "One-time + Repeat = buyers", str(len(buyers)), str(one+rep), one+rep==len(buyers))
        add("GV2-14", "No-purchase is excluded from buyer denominator", str(len(self.customer_360)), str(len(buyers)+len(no_purchase)), len(buyers)+len(no_purchase)==len(self.customer_360))
        seg_missing = int(buyers["customer_segment"].isna().sum())
        seg_invalid = int((~buyers["customer_segment"].isin(SEGMENT_ORDER)).sum())
        add("GV2-15", "Every buyer has exactly one valid F/M segment", "0 missing / 0 invalid", f"missing={seg_missing}; invalid={seg_invalid}", seg_missing==0 and seg_invalid==0)

        expected_aov = buyers["total_net_sales"] / buyers["order_count"]
        expected_basket = buyers["total_quantity"] / buyers["order_count"]
        add("GV2-16", "Customer AOV and Basket Size match formulas", "max diff = 0 at stored precision",
            f"aov={_max_abs_diff(buyers.avg_order_value, expected_aov.round(2)):.6f}; basket={_max_abs_diff(buyers.avg_basket_size, expected_basket.round(4)):.6f}",
            _max_abs_diff(buyers.avg_order_value, expected_aov.round(2))<=1e-9 and _max_abs_diff(buyers.avg_basket_size, expected_basket.round(4))<=1e-9)
        add("GV2-17", "Historical CLV = total_net_sales", "max diff = 0", f"max_diff={_max_abs_diff(self.customer_360.historical_clv, self.customer_360.total_net_sales):.6f}", _max_abs_diff(self.customer_360.historical_clv, self.customer_360.total_net_sales)<=1e-9)

        pref_counts = self.customer_category[self.customer_category["is_preferred_category"]].groupby("customer_id").size()
        add("GV2-18", "Exactly one preferred category per buyer", f"{len(buyers)} buyers", f"buyers_with_pref={len(pref_counts)}; max_pref_per_customer={int(pref_counts.max()) if len(pref_counts) else 0}", len(pref_counts)==len(buyers) and (pref_counts==1).all())

        monthly_sales = float(self.customer_monthly["net_sales"].sum())
        category_sales = float(self.customer_category["net_sales"].sum())
        add("GV2-19", "Monthly mart total = Gold order total", f"diff <= {tol}", f"diff={abs(monthly_sales-order_gold):.6f}", abs(monthly_sales-order_gold)<=tol)
        add("GV2-20", "Category mart total = Gold line total", f"diff <= {tol}", f"diff={abs(category_sales-line_gold):.6f}", abs(category_sales-line_gold)<=tol)

        for grain, vid in [("MONTH","GV2-21"),("DAY_OF_WEEK","GV2-22")]:
            x = self.customer_time[self.customer_time["time_grain"]==grain]
            d = abs(float(x["net_sales"].sum()) - order_gold)
            add(vid, f"{grain} time mart total = Gold order total", f"diff <= {tol}", f"diff={d:.6f}", d<=tol)

        seg_count = int(self.segment_summary["customer_count"].sum())
        seg_sales = float(self.segment_summary["net_sales"].sum())
        add("GV2-23", "Segment summary covers all buyers", str(len(buyers)), str(seg_count), seg_count==len(buyers))
        add("GV2-24", "Segment summary Net Sales = buyer Net Sales", f"diff <= {tol}", f"diff={abs(seg_sales-float(buyers.total_net_sales.sum())):.6f}", abs(seg_sales-float(buyers.total_net_sales.sum()))<=tol)

        # Preserve status counts exactly within selected scope.
        dw_status = self.dw_order_scope.merge(self.dim_status, on="order_status_key", how="left")["order_status"].value_counts().sort_index()
        gold_status = self.fact_order["order_status"].value_counts().sort_index()
        status_ok = dw_status.equals(gold_status)
        add("GV2-25", "Order-status counts preserved DW -> Gold", "Exact match", json.dumps(gold_status.to_dict(), ensure_ascii=False), status_ok)

        # For ALL-status mode, the existing DW periodic snapshot should reconcile with derived monthly Gold.
        if not self.included_statuses:
            snap = self.dw_monthly_snapshot.copy()
            snap = snap.merge(self.dim_customer[["customer_key","customer_id"]], on="customer_key", how="left", validate="many_to_one")
            snap = snap.merge(self.dim_date[["date_key","year_month"]].rename(columns={"date_key":"snapshot_month_key"}), on="snapshot_month_key", how="left", validate="many_to_one")
            s = snap.groupby(["customer_id","year_month"], as_index=False).agg(
                orders=("monthly_order_count","sum"), units=("monthly_quantity","sum"), net_sales=("monthly_net_sales","sum")
            ).sort_values(["customer_id","year_month"]).reset_index(drop=True)
            g = self.customer_monthly[["customer_id","year_month","orders","units","net_sales"]].sort_values(["customer_id","year_month"]).reset_index(drop=True)
            row_ok = len(s)==len(g)
            if row_ok:
                key_ok = s[["customer_id","year_month"]].astype(str).equals(g[["customer_id","year_month"]].astype(str))
                measure_diff = max(
                    _max_abs_diff(s["orders"], g["orders"]),
                    _max_abs_diff(s["units"], g["units"]),
                    _max_abs_diff(s["net_sales"], g["net_sales"]),
                )
            else:
                key_ok, measure_diff = False, float("inf")
            add("GV2-26", "Gold monthly mart reconciles with DW periodic snapshot (ALL status)", "Same grain/rows/measures",
                f"dw_rows={len(s)}; gold_rows={len(g)}; max_measure_diff={measure_diff:.6f}", row_ok and key_ok and measure_diff<=tol)

    def build_reconciliation(self):
        scoped_payment = float(self.dw_order_scope["payment_value"].sum())
        rows = [
            ("Scoped DW FACT_SALES_LINE rows", len(self.dw_line_scope), len(self.fact_item)),
            ("Scoped DW FACT_ORDER rows", len(self.dw_order_scope), len(self.fact_order)),
            ("DW DIM_CUSTOMER rows", len(self.dim_customer), len(self.customer_360)),
            ("DW line Net Sales -> Gold line Net Sales", float(self.dw_line_scope.net_sales.sum()), float(self.fact_item.line_net_sales.sum())),
            ("DW order value -> Gold order value", float(self.dw_order_scope.order_value.sum()), float(self.fact_order.order_value.sum())),
            ("DW payment value -> Gold order value", scoped_payment, float(self.fact_order.order_value.sum())),
            ("Gold order value -> Customer 360 total", float(self.fact_order.order_value.sum()), float(self.customer_360.total_net_sales.sum())),
            ("Gold order value -> Monthly mart total", float(self.fact_order.order_value.sum()), float(self.customer_monthly.net_sales.sum())),
            ("Gold line sales -> Category mart total", float(self.fact_item.line_net_sales.sum()), float(self.customer_category.net_sales.sum())),
        ]
        self.reconciliation_rows = []
        for name, source, target in rows:
            if isinstance(source, (float,np.floating)) or isinstance(target,(float,np.floating)):
                diff = float(target)-float(source)
                ok = abs(diff) <= self.tolerance
            else:
                diff = int(target)-int(source)
                ok = diff == 0
            self.reconciliation_rows.append({
                "reconciliation": name, "source_value": source, "target_value": target,
                "difference": diff, "status": "PASS" if ok else "FAIL"
            })

