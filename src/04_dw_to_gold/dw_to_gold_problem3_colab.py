"""
Problem 3 Gold V2 ETL - DW -> Customer Analytics Data Mart
============================================================

Input
-----
A Problem 3 dimensional Data Warehouse package generated by 3nf_to_dw_colab.py,
either a ZIP file (for example dw_problem3.zip) or a directory containing:

  dimensions/
    DIM_DATE.csv
    DIM_CUSTOMER.csv
    DIM_GEOGRAPHY.csv
    DIM_PRODUCT.csv
    DIM_ORDER_STATUS.csv
  facts/
    FACT_SALES_LINE.csv.gz
    FACT_ORDER.csv.gz
    FACT_CUSTOMER_MONTHLY_SNAPSHOT.csv.gz

Output
------
Gold V2 preserves the Gold V1 analytical contract so the existing EDA can be
reused, but its authoritative source is now the DW layer:

  gold_problem3_v2/
    facts/
      FACT_CUSTOMER_ORDER_ITEM.csv.gz
      FACT_CUSTOMER_ORDER.csv.gz
    marts/
      MART_CUSTOMER_360.csv
      MART_CUSTOMER_MONTHLY.csv
      MART_CUSTOMER_CATEGORY.csv
      MART_CUSTOMER_TIME.csv
      MART_CUSTOMER_SEGMENT_SUMMARY.csv
    reports/
      gold_validation_v2.csv
      gold_reconciliation_v2.csv
      gold_schema_dictionary_v2.csv
      gold_lineage_v2.csv
      gold_run_metadata_v2.csv
    README.txt

Business rules
--------------
- Net Sales = quantity * unit_price - discount_amount (DW already carries net_sales)
- Frequency = COUNT(DISTINCT order_id) per customer
- Monetary = SUM(order_value) per customer
- F/M cutoffs = medians among customers with >= 1 analyzed order
- VIP = High F + High M
- High-value = Low F + High M
- Potential = High F + Low M
- Low-value = Low F + Low M
- One-time = 1 order; Repeat = >=2; No-purchase = 0
- AOV = Total Net Sales / Number of Orders
- Basket Size = Total Quantity / Number of Orders
- Historical CLV = observed total Net Sales per customer
- Preferred Category = max customer-category Net Sales; tie by Units DESC then Category ASC
- Time analysis = MONTH and DAY_OF_WEEK only (no time-of-day source)

Order-status policy
-------------------
Default is ALL statuses preserved by the DW. Nothing is silently filtered.
Optionally use --included-statuses delivered,paid,shipped to create a scoped
Gold V2. If a filter is used, all customer metrics, segment thresholds and marts
are recomputed from the filtered DW facts.

Example (Google Colab)
-----------------------
!python /content/dw_to_gold_problem3_colab.py \\
    --input /content/dw_problem3.zip \\
    --output /content/gold_problem3_v2
"""

